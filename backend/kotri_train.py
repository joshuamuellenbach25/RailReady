def _zip_path(rid):
    p = os.path.join(cal.stage_dir(rid), "kotri.zip")
    return p if os.path.exists(p) else None


def load_bytes(rec: dict, zf: zipfile.ZipFile | None) -> bytes:
    data = zf.read(kotri.SOURCE["prefix"] + rec["path"]) if zf else storage.get_object(rec["object_path"])
    if hashlib.sha256(data).hexdigest() != rec["sha256"]:
        raise RuntimeError(f"hash mismatch for {rec['path']}")
    return data


# ---------- features (pure numpy; deterministic) ----------
def features(img: Image.Image, flip=False) -> np.ndarray:
    g = ImageOps.grayscale(img).resize((160, 90), Image.BILINEAR)
    if flip:
        g = ImageOps.mirror(g)
    a = np.asarray(g, dtype=np.float32) / 255.0
    rgb = np.asarray(img.resize((80, 45)), dtype=np.float32) / 255.0
    thumb = np.asarray(g.resize((16, 9), Image.BILINEAR), dtype=np.float32).ravel() / 255.0
    gx = np.zeros_like(a); gy = np.zeros_like(a)
    gx[:, 1:-1] = a[:, 2:] - a[:, :-2]; gy[1:-1, :] = a[2:, :] - a[:-2, :]
    mag = np.hypot(gx, gy); ang = (np.arctan2(gy, gx) % np.pi) / np.pi * 8
    hog = []
    for cy in range(4):
        for cx in range(4):
            sl = (slice(cy * 22, (cy + 1) * 22), slice(cx * 40, (cx + 1) * 40))
            h = np.bincount(np.minimum(ang[sl].astype(int).ravel(), 7), weights=mag[sl].ravel(), minlength=8)
            hog.append(h / (h.sum() + 1e-6))
    lap = a[1:-1, 1:-1] * 4 - a[:-2, 1:-1] - a[2:, 1:-1] - a[1:-1, :-2] - a[1:-1, 2:]
    hist = np.histogram(a, bins=16, range=(0, 1))[0] / a.size
    stats = [a.mean(), a.std(), float(np.var(lap)), float((mag > 0.1).mean()), float((mag > 0.25).mean()),
             *rgb.reshape(-1, 3).mean(0), *rgb.reshape(-1, 3).std(0), float(np.abs(lap).mean())]
    return np.concatenate([thumb, np.concatenate(hog), hist, np.asarray(stats, dtype=np.float32)]).astype(np.float64)


def train_softmax(X, y, k, l2=1e-3, iters=500, lr=0.05, seed=7):
    mu, sd = X.mean(0), X.std(0) + 1e-6
    Z = (X - mu) / sd
    rng = np.random.default_rng(seed)
    W = rng.normal(0, 0.01, (Z.shape[1], k)); b = np.zeros(k)
    cnt = np.bincount(y, minlength=k).astype(float)
    cw = np.where(cnt > 0, len(y) / (k * np.maximum(cnt, 1)), 0.0)  # class-balanced
    sw = cw[y]; Y = np.eye(k)[y]
    mW = vW = np.zeros_like(W); mb = vb = np.zeros_like(b); losses = []
    for t in range(1, iters + 1):
        S = Z @ W + b; S -= S.max(1, keepdims=True); P = np.exp(S); P /= P.sum(1, keepdims=True)
        G = (P - Y) * sw[:, None] / len(y)
        gW = Z.T @ G + l2 * W; gb = G.sum(0)
        mW = 0.9 * mW + 0.1 * gW; vW = 0.999 * vW + 0.001 * gW ** 2; mb = 0.9 * mb + 0.1 * gb; vb = 0.999 * vb + 0.001 * gb ** 2
        W -= lr * (mW / (1 - 0.9 ** t)) / (np.sqrt(vW / (1 - 0.999 ** t)) + 1e-8)
        b -= lr * (mb / (1 - 0.9 ** t)) / (np.sqrt(vb / (1 - 0.999 ** t)) + 1e-8)
        if t % 50 == 0:
            losses.append({"iter": t, "weighted_log_loss": float(-(sw * np.log(P[np.arange(len(y)), y] + 1e-9)).mean())})
    return {"W": W, "b": b, "mu": mu, "sd": sd, "class_weights": cw.tolist()}, losses


def logits(m, X):
    return ((X - m["mu"]) / m["sd"]) @ m["W"] + m["b"]


def softmax(S, T=1.0):
    S = S / T; S = S - S.max(1, keepdims=True); P = np.exp(S)
    return P / P.sum(1, keepdims=True)


def fit_temperature(S, y):
    best = (None, 1.0)
    for T in np.exp(np.linspace(np.log(0.25), np.log(8), 120)):
        nll = float(-np.log(softmax(S, T)[np.arange(len(y)), y] + 1e-12).mean())
        if best[0] is None or nll < best[0]:
            best = (nll, float(T))
    return best[1], best[0]


def evaluate(y, P, k=len(CLASSES), bins=10) -> dict:
    pred = P.argmax(1)
    conf = np.zeros((k, k), dtype=int)
    for t, p in zip(y, pred):
        conf[t, p] += 1
    per = {}
    for i, c in enumerate(CLASSES):
        sup, tp, pp = int(conf[i].sum()), int(conf[i, i]), int(conf[:, i].sum())
        rec = tp / sup if sup else None
        prec = tp / pp if pp else None
        f1 = (2 * prec * rec / (prec + rec) if prec and rec else 0.0) if sup else None
        per[c] = {"support": sup, "predicted": pp, "recall": rec and round(rec, 4), "precision": prec and round(prec, 4),
                  "f1": None if f1 is None else round(f1, 4), "note": None if sup else "zero support in this split. Metric unavailable"}
    sup_cls = [c for c in CLASSES if per[c]["support"]]
    top2 = float(np.mean([t in np.argsort(-p)[:2] for t, p in zip(y, P)])) if len(y) else None
    cmax = P.max(1); ok = (pred == y); ece = 0.0; rel = []
    for j in range(bins):
        lo, hi = j / bins, (j + 1) / bins
        mk = (cmax >= lo) & ((cmax < hi) if j < bins - 1 else (cmax <= hi)); n = int(mk.sum())
        if n:
            ece += n / len(y) * abs(float(cmax[mk].mean()) - float(ok[mk].mean()))
        rel.append({"bin": [lo, hi], "n": n, "mean_confidence": round(float(cmax[mk].mean()), 4) if n else None, "accuracy": round(float(ok[mk].mean()), 4) if n else None})
    return {"n": int(len(y)), "classes": CLASSES, "confusion": conf.tolist(), "per_class": per, "supported_classes": sup_cls,
            "accuracy": round(float(ok.mean()), 4) if len(y) else None,
            "balanced_accuracy": round(float(np.mean([per[c]["recall"] for c in sup_cls])), 4) if sup_cls else None,
            "macro_f1": round(float(np.mean([per[c]["f1"] for c in sup_cls])), 4) if sup_cls else None,
            "top2_accuracy": top2 and round(top2, 4), "nll": round(float(-np.log(P[np.arange(len(y)), y] + 1e-12).mean()), 4) if len(y) else None,
            "ece_top_label": round(ece, 5), "reliability_bins": rel,
            "healthy_false_positive_rate": None, "healthy_note": "No healthy class in source. Unmeasured."}


async def _log(rid, msg):
    await db.model_runs.update_one({"uuid": rid}, {"$push": {"logs": {"at": iso(), "msg": msg}}, "$set": {"updated_at": iso()}})


async def _split(release_id, split):
    return await db.kotri_images.find({"release_id": release_id, "split": split, "representative": True, "verified": True},
                                      {"_id": 0}).sort("path", 1).to_list(10000)


def _extract(release_id, recs, flip_aug=False):
    zp = _zip_path(release_id)
    zf = zipfile.ZipFile(zp) if zp else None
    X, y, keys = [], [], []
    for r in recs:
        img = Image.open(io.BytesIO(load_bytes(r, zf))).convert("RGB")
        X.append(features(img)); y.append(CLASSES.index(r["label"])); keys.append(r["path"])
        if flip_aug:
            X.append(features(img, flip=True)); y.append(CLASSES.index(r["label"])); keys.append(r["path"] + "#flip")
    return np.asarray(X), np.asarray(y), keys


async def run_train(job):
    run = await db.model_runs.find_one({"uuid": job["target_id"]})
    rid, rel_id = run["uuid"], run["release_id"]
    t0 = time.time()
    await db.model_runs.update_one({"uuid": rid}, {"$set": {"status": "Running", "started_at": iso()}})
    fit, calib, test = await _split(rel_id, "fit"), await _split(rel_id, "calibration"), await _split(rel_id, "test")
    await _log(rid, f"fit {len(fit)} / calibration {len(calib)} / test {len(test)} representative images")
    Xf, yf, _ = await cal.run_blocking(_extract, rel_id, fit, True)
    await cal.heartbeat(job)
    await _log(rid, f"fit features {Xf.shape} (with horizontal-flip augmentation)")
    model, losses = await cal.run_blocking(train_softmax, Xf, yf, len(CLASSES))
    buf = io.BytesIO()
    np.savez(buf, W=model["W"], b=model["b"], mu=model["mu"], sd=model["sd"])
    ck = buf.getvalue(); ck_sha = hashlib.sha256(ck).hexdigest()
    path = f"{kotri.obj_path(run['workspace_id'], rel_id, 'models')}/{rid}.npz"
    await cal.run_blocking(storage.put_object, path, ck, "application/octet-stream")
    if hashlib.sha256(await cal.run_blocking(storage.get_object, path)).hexdigest() != ck_sha:
        raise RuntimeError("checkpoint re-verify failed")
    await _log(rid, f"checkpoint frozen sha256 {ck_sha}")
    await cal.heartbeat(job)
    Xc, yc, _ = await cal.run_blocking(_extract, rel_id, calib)
    T, nll = fit_temperature(logits(model, Xc), yc)
    await _log(rid, f"temperature T={T:.4f} fit on calibration split (classes present: {sorted({CLASSES[i] for i in set(yc.tolist())})})")
    await cal.heartbeat(job)
    Xt, yt, _ = await cal.run_blocking(_extract, rel_id, test)
    St = logits(model, Xt)
    prior = np.bincount(yf, minlength=len(CLASSES)) / len(yf)
    res = {
        "trained_uncalibrated": evaluate(yt, softmax(St)),
        "trained_temperature_scaled": evaluate(yt, softmax(St, T)),
        "baseline_fit_prior": evaluate(yt, np.tile(prior, (len(yt), 1))),
        "calibration_split_temperature_scaled": evaluate(yc, softmax(logits(model, Xc), T)),
    }
    await db.model_runs.update_one({"uuid": rid}, {"$set": {
        "status": "Done", "losses": losses, "checkpoint": {"path": path, "sha256": ck_sha, "bytes": len(ck)},
        "temperature": {"T": T, "calibration_nll": nll, "fit_on": "calibration split only (fit/test untouched)",
                        "classes_present": sorted({CLASSES[i] for i in set(yc.tolist())}),
                        "note": "crack, groove, joint have zero calibration support. Their calibration is unsupported"},
        "results": res, "domain": DOMAIN, "features": "grayscale 16×9 thumbnail + 4×4 gradient-orientation histograms + 16-bin intensity histogram + intensity/colour stats (300-d)",
        "model": "multinomial logistic regression, class-balanced, Adam 500 iters, L2 1e-3", "test_locked": True,
        "counts": {"fit": len(fit), "fit_with_aug": int(len(yf)), "calibration": len(calib), "test": len(test)},
        "duration_s": round(time.time() - t0, 1), "completed_at": iso()}})
    return "Done"


async def run_smoke(job):
    run = await db.model_runs.find_one({"uuid": job["target_id"]})
    rid, rel_id = run["uuid"], run["release_id"]
    from emergentintegrations.llm.chat import ImageContent, LlmChat, UserMessage
    model_id = os.environ.get("IMAGE_MODEL_ID", "claude-sonnet-5-5")
    await db.model_runs.update_one({"uuid": rid}, {"$set": {"status": "Running", "started_at": iso(), "model_id": model_id, "prompt_version": SMOKE_PROMPT_VERSION}})
    zp = _zip_path(rel_id); zf = zipfile.ZipFile(zp) if zp else None
    items = []
    for c in CLASSES:
        r = await db.kotri_images.find_one({"release_id": rel_id, "split": "fit", "label": c, "representative": True}, {"_id": 0}, sort=[("path", 1)])
        if not await cal.reserve_call(1):
            items.append({"label": c, "status": "budget_limited", "error": cal.BUDGET_MSG}); break
        data = load_bytes(r, zf)
        t0 = time.time()
        entry = {"label_withheld": True, "path": r["path"], "label": c, "image_sha256": r["sha256"], "model_id": model_id, "prompt_version": SMOKE_PROMPT_VERSION}
        try:
            chat = LlmChat(api_key=os.environ["EMERGENT_LLM_KEY"], session_id=f"{rid}-{c}", system_message="You inspect rail surfaces. Output JSON only.").with_model("anthropic", model_id)
            resp = await chat.send_message(UserMessage(text=SMOKE_PROMPT, file_contents=[ImageContent(image_base64=base64.b64encode(data).decode())]))
            entry.update({"raw_response": resp, "latency_s": round(time.time() - t0, 2)})
            await db.model_runs.update_one({"uuid": rid}, {"$push": {"items": dict(entry)}})  # raw first
            try:
                import photo_analysis_rules as R
                from photo_pipeline import extract_json
                a = extract_json(resp)
                R.validate_distribution(a, SMOKE_CHOICES)
                entry.update({"choice": a["choice"], "correct": a["choice"] == c, "status": "ok", "probabilities": a["probabilities"]})
            except Exception as e:
                entry.update({"status": "invalid_output", "error": str(e)[:300]})
        except Exception as e:
            entry.update({"status": "provider_error", "error": f"{type(e).__name__}: {e}"[:300], "latency_s": round(time.time() - t0, 2)})
        items.append(entry)
        await cal.heartbeat(job)
    ok = [i for i in items if i.get("status") == "ok"]
    await db.model_runs.update_one({"uuid": rid}, {"$set": {
        "status": "Done", "items": items, "summary": {"calls": len([i for i in items if "latency_s" in i]), "valid": len(ok),
                                                      "correct": sum(1 for i in ok if i["correct"]),
                                                      "note": "Smoke only (1 image per class). Not an accuracy estimate."},
        "domain": DOMAIN, "budget_after": await cal.budget(), "completed_at": iso()}})
    return "Done"


cal.HANDLERS["kotri_train"] = run_train
cal.HANDLERS["kotri_smoke"] = run_smoke
